/** @param {string} pathname */
export function getLocaleFromPath(pathname) {
  return pathname.split("/").filter(Boolean)[0] === "en" ? "en" : "ko";
}

/** @param {"ko" | "en"} locale @param {string} [pathname] */
export function localePath(locale, pathname = "/") {
  const pathWithoutLocale = pathname.replace(/^\/(en)(?=\/|$)/, "") || "/";
  const normalizedPath = pathWithoutLocale.startsWith("/") ? pathWithoutLocale : `/${pathWithoutLocale}`;
  return locale === "en" ? `/en${normalizedPath === "/" ? "/" : normalizedPath}` : normalizedPath;
}

/** @param {"ko" | "en"} locale @param {keyof typeof messages.ko} key */
export function translate(locale, key) {
  return messages[locale][key] ?? messages.ko[key] ?? key;
}
